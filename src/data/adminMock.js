export function getClientById(id) {
  return adminClients.find((c) => c.id === id) || null
}

export function getClientAggregates(id) {
  const devis = adminDevis.filter((d) => d.clientId === id)
  const missions = adminMissions.filter((m) => m.clientId === id)
  const factures = adminFactures.filter((f) => f.clientId === id)
  const demandes = adminDemandes.filter((d) => d.clientId === id)
  const reclamations = adminReclamations.filter((r) => r.clientId === id)

  const facturesPaid = factures.filter((f) => f.status === 'paid').reduce((s, f) => s + f.amount, 0)
  const facturesPending = factures.filter((f) => f.status !== 'paid').reduce((s, f) => s + f.amount, 0)

  return { devis, missions, factures, demandes, reclamations, facturesPaid, facturesPending }
}

