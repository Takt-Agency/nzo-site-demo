export function findProductBySlug(slug) {
  return products.find((p) => p.slug === slug)
}

export function getRelatedProducts(productId, category, limit = 4) {
  return products
    .filter((p) => p.id !== productId && (p.category === category || category === 'all'))
    .slice(0, limit)
}
